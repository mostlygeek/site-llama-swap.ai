#!/usr/bin/env bash
#
# Copy the parts of llama-swap that power the Help agent into
# internal/llamaswap/.
#
# The packages live under llama-swap's internal/ directory, which Go does not
# allow another module to import, so they are copied here with their import
# paths rewritten. Run this again to pick up new documentation or code from
# llama-swap, then commit the result.
#
# Usage: scripts/sync-llama-swap.sh [path to a llama-swap checkout]
#        (defaults to ../llama-swap)

set -euo pipefail

SITE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$(cd "${1:-$SITE_ROOT/../llama-swap}" && pwd)"
DEST="$SITE_ROOT/internal/llamaswap"

UPSTREAM_MODULE="github.com/mostlygeek/llama-swap"
SITE_MODULE="github.com/mostlygeek/site-llama-swap.ai/internal/llamaswap"

if [[ ! -f "$SRC/go.mod" ]] || ! grep -q "^module $UPSTREAM_MODULE\$" "$SRC/go.mod"; then
	echo "error: $SRC is not a llama-swap checkout" >&2
	exit 1
fi

COMMIT="$(git -C "$SRC" rev-parse HEAD)"
if [[ -n "$(git -C "$SRC" status --porcelain -- internal/docagent internal/mcptools docs config-schema.json ui/src)" ]]; then
	echo "warning: $SRC has uncommitted changes; recording $COMMIT anyway" >&2
fi

echo "syncing llama-swap $COMMIT from $SRC"

# Everything under internal/llamaswap is written by this script.
rm -rf "$DEST"
mkdir -p "$DEST/docagent" "$DEST/mcptools/sourcecode" "$DEST/docs" "$DEST/source"

# copy_go copies the non-test Go files of one package.
copy_go() {
	local from="$1" to="$2"
	find "$SRC/$from" -maxdepth 1 -name '*.go' ! -name '*_test.go' -exec cp {} "$DEST/$to/" \;
}

copy_go internal/docagent docagent
copy_go internal/mcptools mcptools
copy_go internal/mcptools/sourcecode mcptools/sourcecode

# llama-swap embeds its own source behind a build tag. The site supplies the
# source itself (see internal/llamaswap/source), so those files are dropped.
rm -f "$DEST/mcptools/sourcecode/embed.go" "$DEST/mcptools/sourcecode/embed_nosrc.go"

# Rewrite imports of llama-swap's internal packages to the copies.
find "$DEST" -name '*.go' -exec sed -i \
	-e "s#\"$UPSTREAM_MODULE/internal/#\"$SITE_MODULE/#g" {} +

# Documentation: the knowledge base, config example, README and schema.
cp -R "$SRC/docs/kb" "$DEST/docs/kb"
cp "$SRC/docs/config.example.yaml" "$SRC/docs/README.md" "$DEST/docs/"
cp "$SRC/config-schema.json" "$DEST/docs/"

# The Docs Agent system prompt, unescaped from its TypeScript template literal.
# The model was fine-tuned on this prompt, so it is used as is; the server only
# drops the lines for tools the website does not have.
python3 - "$SRC/ui/src/lib/prompts/docsAgent.ts" "$DEST/docs/docs-agent-prompt.md" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
m = re.search(r"export const DOCS_AGENT_SYSTEM_PROMPT = `(.*?)`;", src, re.S)
if not m:
    sys.exit("could not find DOCS_AGENT_SYSTEM_PROMPT in " + sys.argv[1])
text = m.group(1)
if "${" in text:
    sys.exit("DOCS_AGENT_SYSTEM_PROMPT uses ${} interpolation, which this script cannot expand")
text = text.replace("\\`", "`").replace("\\\\", "\\")
open(sys.argv[2], "w", encoding="utf-8").write(text + "\n")
PY

cat >"$DEST/docs/embed.go" <<'EOF'
// Code generated by scripts/sync-llama-swap.sh. DO NOT EDIT.

// Package docs embeds llama-swap's documentation, served by the Help agent's
// docs__* tools.
package docs

import "embed"

// Files holds the knowledge base, config example and README, laid out as
// llama-swap's docs/ directory so docagent can read it unchanged.
//
//go:embed kb config.example.yaml README.md
var Files embed.FS

// ConfigSchema is llama-swap's config-schema.json.
//
//go:embed config-schema.json
var ConfigSchema []byte

// AgentPrompt is the Docs Agent system prompt from llama-swap's UI.
//
//go:embed docs-agent-prompt.md
var AgentPrompt string
EOF

# The source behind the code__* tools: the same files llama-swap's `make src`
# embeds (Go and TypeScript without tests), stored as one tarball so the site
# repository does not carry hundreds of copied files. The tar options make the
# archive byte-identical for the same commit.
git -C "$SRC" ls-files -z --cached -- '*.go' 'ui/*.ts' 'ui/*.svelte' \
	':(exclude)*_test.go' ':(exclude)*.test.ts' |
	tar -C "$SRC" -cf - --null -T - --sort=name --mtime='2000-01-01 00:00Z' \
		--owner=0 --group=0 --numeric-owner --format=gnu |
	gzip -9n >"$DEST/source/llama-swap-src.tar.gz"

cat >"$DEST/source/embed.go" <<EOF
// Code generated by scripts/sync-llama-swap.sh. DO NOT EDIT.

// Package source embeds llama-swap's source code for the code__* tools.
package source

import _ "embed"

// Commit is the llama-swap commit everything under internal/llamaswap was
// copied from.
const Commit = "$COMMIT"

// Tarball is a gzipped tar of llama-swap's Go and TypeScript files, without
// tests, at Commit.
//
//go:embed llama-swap-src.tar.gz
var Tarball []byte
EOF

gofmt -w "$DEST"
echo "done: $(find "$DEST" -name '*.go' | wc -l) Go files, $(find "$DEST/docs/kb" -name '*.md' | wc -l) kb files"
